import os from "node:os";
import path from "node:path";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { createRuntimeBridgeBackend } from "../../../../../role-model-router/apps/runtime-host-bridge/src/index.ts";
import { bootstrapQaControlPlane, createQaFixtureRoot, createQaRuntimeConfigPath, createQaRuntimeConfigText } from "../../../../../role-model-router/apps/runtime-host-bridge/scripts/start-for-qa.ts";
const repoRoot = path.resolve(import.meta.dirname, "../../../../..");
const runtimeStateRoot = path.join(os.tmpdir(), "role-model-runtime-qa-probe");
const scopeId = "runtime-qa-probe";
const unifiedRuntimeConfigPath = createQaRuntimeConfigPath(runtimeStateRoot);
console.log("probe:start", repoRoot);
await rm(runtimeStateRoot, { recursive: true, force: true });
await mkdir(runtimeStateRoot, { recursive: true });
await writeFile(unifiedRuntimeConfigPath, createQaRuntimeConfigText(), "utf8");
console.log("probe:before backend");
const backendPromise = createRuntimeBridgeBackend({ fixtureRoot: createQaFixtureRoot(repoRoot), repoRoot, runtimeStateRoot, scopeId, unifiedRuntimeConfigPath });
const backend = await Promise.race([backendPromise, new Promise((_, reject) => setTimeout(() => reject(new Error("backend timeout")), 10000))]);
console.log("probe:after backend");
await Promise.race([bootstrapQaControlPlane(backend), new Promise((_, reject) => setTimeout(() => reject(new Error("bootstrap timeout")), 10000))]);
console.log("probe:after bootstrap");
await backend.shutdown();
console.log("probe:done");
